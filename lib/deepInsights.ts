import type { DeepResult } from './deep';

export interface DeepInsight {
  id: string;
  tone: 'info' | 'positive' | 'attention';
  title: string;
  text: string;
  refs: string[];
}

const HIGH = 62;
const LOW = 38;
const pct = (n: number) => `${Math.round(n)} %`;

/**
 * Выводы по скрытым измерениям. Правила простые и открытые; формулировки осторожные.
 * Это описание ваших ответов и их сочетаний, а не диагноз.
 */
export function buildDeepInsights(r: DeepResult): DeepInsight[] {
  const out: DeepInsight[] = [];
  const t = (id: string) => r.by[id]?.theta ?? null;
  const hi = (id: string) => (t(id) ?? -1) >= HIGH;
  const lo = (id: string) => (t(id) ?? 101) <= LOW;
  const title = (id: string) => r.by[id].def.title.replace(/\s*\(.*\)$/, '').toLowerCase();

  // 1. Метачерты (Digman; DeYoung)
  const { stability, plasticity } = r.bigTwo;
  if (stability !== null && plasticity !== null) {
    const s = stability >= 50;
    const p = plasticity >= 50;
    const text = s && p
      ? 'Высокая стабильность и высокая пластичность: вы одновременно устойчивы (спокойны, добросовестны, доброжелательны) и открыты новому (общительны, любознательны).'
      : s
        ? 'Высокая стабильность при умеренной пластичности: упор на устойчивость, порядок и согласие с окружением; новизна и риск привлекают меньше.'
        : p
          ? 'Высокая пластичность при невысокой стабильности: любознательность и энергия сочетаются с большей эмоциональной уязвимостью и меньшей склонностью к порядку.'
          : 'Невысокие стабильность и пластичность: вы осторожны и сдержанны, и в стрессовых ситуациях вам может не хватать опоры; помогают ясные рамки и поддержка.';
    out.push({ id: 'bigtwo', tone: 'info', title: `Метачерты: стабильность ${pct(stability)}, пластичность ${pct(plasticity)}`, text: `${text} Метачерты — два широких фактора над пятью чертами; здесь они получены усреднением пяти измерений.`, refs: ['digman1997', 'deyoung2002'] });
  }

  // 2. Трёхфакторная модель аффекта
  const dist = t('DIST');
  const pa = t('LOWPA');
  const ar = t('AROUSAL');
  if (dist !== null && hi('DIST') && pa !== null && ar !== null) {
    if (hi('LOWPA') && !hi('AROUSAL')) {
      out.push({ id: 'tri-dep', tone: 'attention', title: 'Дистресс со снижением интереса и радости', refs: ['watson1991', 'kotov2017'],
        text: `Общий дистресс (${pct(dist)}) сочетается со сниженным положительным переживанием (${pct(pa)}) без выраженного тревожного возбуждения. По трёхфакторной модели Кларк и Уотсона это ближе к профилю сниженного настроения. Стоит обсудить его со специалистом.` });
    } else if (hi('AROUSAL') && !hi('LOWPA')) {
      out.push({ id: 'tri-anx', tone: 'attention', title: 'Дистресс с тревожным возбуждением', refs: ['watson1991', 'kotov2017'],
        text: `Общий дистресс (${pct(dist)}) сочетается с тревожным возбуждением (${pct(ar)}) при сохранном положительном переживании. Это ближе к тревожному профилю: помогают регулярный сон, снижение нагрузки, техники расслабления и разговор со специалистом, если напряжение мешает жить.` });
    } else if (hi('LOWPA') && hi('AROUSAL')) {
      out.push({ id: 'tri-mix', tone: 'attention', title: 'Дистресс с тревогой и сниженным интересом', refs: ['watson1991', 'caspi2014'],
        text: 'Выражены и тревожное возбуждение, и снижение интереса и радости. Симптомы тревоги и подавленности часто идут вместе (общий фактор): это повод обратиться к специалисту, а не пытаться справиться в одиночку.' });
    }
  }

  // 3. Черта и состояние
  if (hi('DIST') && lo('ES')) {
    out.push({ id: 'trait-state', tone: 'info', title: 'Черта и текущее состояние совпадают', refs: ['kotov2010', 'kotov2017'],
      text: 'Низкая эмоциональная устойчивость как черта и выраженный дистресс сейчас указывают в одну сторону: нейротизм — один из самых устойчивых факторов уязвимости к тревоге и сниженному настроению. Чувствительные люди особенно выигрывают от регулярного режима, отдыха и поддержки.' });
  } else if (hi('DIST') && hi('ES')) {
    out.push({ id: 'state-only', tone: 'info', title: 'Дистресс при устойчивом характере', refs: ['kotov2010'],
      text: 'Сейчас выражен дистресс, хотя по чертам вы эмоционально устойчивы. Такое состояние чаще связано с обстоятельствами (нагрузка, потери, болезнь), а не с вашим характером, и обычно лучше поддаётся изменениям.' });
  }

  // 4. Самооценки и привязанность
  if (lo('CSE') && hi('ATA')) {
    out.push({ id: 'cse-ata', tone: 'attention', title: 'Низкие самооценки и тревожная привязанность', refs: ['judge2003', 'noftle2006'],
      text: 'Сомнения в себе сочетаются со страхом отвержения в близких отношениях. Это частое сочетание: когда самооценка нестабильна, подтверждение от других становится особенно важным. Помогают опора на собственные достижения и честные разговоры с близкими.' });
  }
  if (hi('CSE') && hi('WB')) {
    out.push({ id: 'cse-wb', tone: 'positive', title: 'Сильные самооценки поддерживают благополучие', refs: ['judge2003', 'steel2008'],
      text: 'Высокие самооценки (самооценка, самоэффективность, устойчивость) сочетаются с хорошим самочувствием. Эти ресурсы стоит беречь в трудные периоды.' });
  }
  if (lo('CONN') && hi('ATV')) {
    out.push({ id: 'conn-atv', tone: 'info', title: 'Дистанция в отношениях', refs: ['noftle2006'],
      text: 'Избегание близости сочетается с ощущением нехватки связей. Это может быть осознанным выбором автономии; если одиночество тяготит, помогают небольшие шаги к сближению в безопасном темпе.' });
  }

  // 5. Круг межличностных отношений
  if (r.circumplex?.octant) {
    const o = r.circumplex.octant;
    out.push({ id: 'circumplex', tone: 'info', title: `Межличностный стиль: ${o.label.toLowerCase()} (${o.code})`, refs: ['wiggins1979'],
      text: `Агентность (самоутверждение) ${pct(r.circumplex.agency)}, коммуналность (теплота) ${pct(r.circumplex.communion)}. В круге Виггинса это сектор «${o.label}». Круг описывает преобладающий стиль общения, а не оценку человека.` });
  }
  if (lo('HH') && lo('COMM') && hi('AGEN')) {
    out.push({ id: 'dark', tone: 'attention', title: 'Профиль ближе к «тёмным» чертам', refs: ['paulhus2002', 'lee2005'],
      text: 'Низкие честность и теплота при высокой агентности — сочетание, которое в исследованиях связывают с макиавеллизмом и нарциссизмом. Это описание склонностей в пределах нормы, а не диагноз; полезно обращать внимание на то, как стиль влияет на людей вокруг.' });
  }

  // 6. Типы Блоков (упрощённо)
  if (r.blockType && r.blockType !== 'mixed') {
    const text = {
      resilient: 'устойчивый: эмоционально стабильный, общительный, доброжелательный и добросовестный профиль',
      overcontrolled: 'сверхконтролирующий: сочетание эмоциональной чувствительности и сдержанности в общении',
      undercontrolled: 'недоконтролирующий: низкие добросовестность и доброжелательность, больше импульсивности и конфликтности',
    }[r.blockType];
    out.push({ id: 'block', tone: 'info', title: 'Ближайший прототип по Блокам', refs: ['robins1996'],
      text: `По упрощённой эвристике (четыре черты) ваш профиль ближе к типу «${text}». Исследования описывают три воспроизводимых типа; здесь это только ориентир, не классификация.` });
  }

  // 7. Нейроразнообразие
  if (hi('ND_AQ') || hi('ND_ADHD')) {
    out.push({ id: 'neuro', tone: 'info', title: 'Результаты скринингов нейроразнообразия', refs: ['kotov2017'],
      text: 'Скрининги показывают, нужна ли дальнейшая оценка, но не причины трудностей. Особенности внимания и социального взаимодействия бывают связаны с чертами (низкая добросовестность, сдержанность) и с эмоциональным состоянием; при сомнениях лучше обратиться к специалисту.' });
  }

  // 8. Косвенные оценки и расхождения
  const indirect = r.dims.filter((d) => d.theta !== null && d.indirect);
  if (indirect.length) {
    out.push({ id: 'indirect', tone: 'info', title: 'Некоторые оценки косвенные', refs: [],
      text: `Для измерений «${indirect.map((d) => d.def.title.replace(/\s*\(.*\)$/, '').toLowerCase()).join('», «')}» нет прямой шкалы: оценка опирается только на родственные тесты и менее надёжна.` });
  }
  // Расхождение считаем значимым, если оно велико и статистически (I² ≥ 50 %), и практически (τ ≥ 10 п. п.).
  const hetero = r.dims
    .filter((d) => d.i2 !== null && d.i2 >= 50 && d.tests >= 2 && Math.sqrt(d.tau2) >= 10)
    .sort((a, b) => b.i2! - a.i2!);
  if (hetero.length) {
    out.push({ id: 'hetero', tone: 'attention', title: 'Тесты по-разному оценивают часть характеристик', refs: ['higgins2002'],
      text: `Заметное расхождение между тестами (I² ≥ 50 %): ${hetero.slice(0, 5).map((d) => `${title(d.def.id)} (I² ${Math.round(d.i2!)} %)`).join('; ')}${hetero.length > 5 ? ` и ещё ${hetero.length - 5}` : ''}. Так бывает из-за разных формулировок и периодов оценки; доверяйте общему направлению, а не точному числу.` });
  }
  const tens = r.dims.filter((d) => d.tension.length >= 2);
  if (tens.length) {
    out.push({ id: 'tension', tone: 'info', title: 'Есть ответы, идущие против общей картины', refs: [],
      text: `По измерениям «${tens.slice(0, 4).map((d) => title(d.def.id)).join('», «')}» часть пунктов из разных тестов противоречит общему выводу. Такие пункты показаны в разделе подробностей: они могут отражать ситуативные обстоятельства или разное понимание формулировок.` });
  }
  return out;
}
