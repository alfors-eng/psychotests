// Одноразовый патч README: целостный профиль.
const fs = require('fs');
let r = fs.readFileSync('README.md', 'utf8');
if (r.includes('## Целостный профиль')) process.exit(0);
const add = `## Целостный профиль

Вкладки страницы /profile: «Целостная картина», «Сводные таблицы», «Диаграммы». Шкалы из разных тестов, которые измеряют одно и то же, объединяются в сводные показатели по соответствиям из \`data/constructs.json\` (например, «Экстраверсия» = IPIP-50, Mini-IPIP, TIPI и HEXACO-60; «Эмоциональная устойчивость» = перевёрнутый нейротизм из тех же тестов). У каждого соответствия есть \`weight\` (1 — прямое, меньше 1 — родственное) и \`invert\` (противоположный полюс).

По каждому показателю считаются: итог (взвешенное среднее положений на шкалах), диапазон между тестами, согласованность (до 20 п. п. — согласуются, до 35 — умеренный разброс, больше — тесты расходятся), уверенность (число тестов и согласованность). Выводы о сочетаниях показателей (\`lib/insights.ts\`) строятся по простым открытым правилам и сформулированы осторожно, без диагнозов. Радары с наложением показывают итог и контуры отдельных тестов; таблицы — итог с разбросом, матрицу «тест × характеристика» и сортируемый список всех шкал.

Чтобы связать новую шкалу с показателем, добавьте её в \`sources\` нужного конструкта в \`data/constructs.json\` и запустите \`npm run validate\` (проверяются тест, шкала и вес).

`;
r = r.replace('## Профиль', add + '## Профиль');
fs.writeFileSync('README.md', r);
console.log('ok');
